# En production, refuser de démarrer avec la clé de développement (publiée
# dans le dépôt) : elle signe les sessions et les jetons CSRF. Le message
# indique quoi faire plutôt que de laisser l'installation vulnérable.
if not DEBUG and SECRET_KEY == INSECURE_DEV_SECRET_KEY:
    raise ImproperlyConfigured(
        "SECRET_KEY n'est pas définie : l'application refuse de démarrer en "
        "production avec la clé de développement du dépôt. Renseignez "
        "SECRET_KEY dans le fichier .env (cp .env.example .env), par exemple "
        "avec : python3 -c \"import secrets; print(secrets.token_urlsafe(50))\"")

# En production, ALLOWED_HOSTS=["*"] laisse passer n'importe quel en-tête Host
# (empoisonnement des liens de réinitialisation, cache). On exige la liste.
if not DEBUG and ALLOWED_HOSTS == ["*"]:
    raise ImproperlyConfigured(
        "ALLOWED_HOSTS n'est pas définie : indiquez dans .env les noms d'hôte "
        "par lesquels l'application est joignable, séparés par des virgules "
        "(ex. ALLOWED_HOSTS=mon-domaine.tn,192.168.1.10).")

