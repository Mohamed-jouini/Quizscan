# ---------------------------------------------------------------------------
# Durcissement en production. L'application sert des données nominatives
# (copies scannées, notes, bulletins) : les cookies de session et CSRF ne
# doivent circuler qu'en HTTPS (assuré par le reverse proxy) et rester
# inaccessibles au JavaScript tiers.
# ---------------------------------------------------------------------------
if not DEBUG:
    SESSION_COOKIE_HTTPONLY = True
    SESSION_COOKIE_SAMESITE = "Lax"
    CSRF_COOKIE_SAMESITE = "Lax"
    X_FRAME_OPTIONS = "DENY"
    SECURE_CONTENT_TYPE_NOSNIFF = True
    SECURE_REFERRER_POLICY = "same-origin"

    # HTTPS=1 (défaut) : les cookies de session et CSRF sont marqués
    # « Secure », le navigateur ne les renvoie donc que sur https://.
    # Si l'application est jointe en http:// — accès direct par l'adresse IP
    # sur un réseau local, sans reverse proxy TLS — il faut HTTPS=0, sinon le
    # navigateur refuse de renvoyer le cookie et la connexion boucle sans
    # message d'erreur. À ne faire que sur un réseau de confiance.
    HTTPS = os.environ.get("HTTPS", "1") not in ("0", "false", "False", "no")
    SESSION_COOKIE_SECURE = HTTPS
    CSRF_COOKIE_SECURE = HTTPS
    # Redirection http -> https : assurée par le reverse proxy. Si ce n'est
    # pas le cas chez vous, passez SECURE_SSL_REDIRECT=1.
    SECURE_SSL_REDIRECT = os.environ.get("SECURE_SSL_REDIRECT", "0") == "1"

